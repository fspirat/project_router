import Foundation
import XCTest
@testable import RouterCore

/// «Обход»: zapret, Telegram через Cloudflare, сервисы напрямую, MyDirect (contract-stage4 §5.4, §10.4–10.6).
final class BypassTests: XCTestCase {

    func zap(_ text: String) throws -> ZapretState {
        return try decodeJSON(ZapretState.self, text)
    }

    func testZapretWorking() throws {
        let i = Zapret.info(try zap(SampleJSON.zapretOn), now: nowT)
        XCTAssertEqual(i.phase, .working)
        XCTAssertEqual(i.tone, .ok)
        XCTAssertEqual(i.summary, "YouTube и Discord — напрямую, с IP провайдера")
        XCTAssertEqual(i.summaryBold, "напрямую")
        XCTAssertEqual(i.counters, "18234\u{00A0}TCP · 5120\u{00A0}QUIC")
        XCTAssertNil(i.errorText)
        XCTAssertTrue(i.isOn)
        XCTAssertTrue(i.showsControls)
        XCTAssertTrue(i.toggleEnabled)
        XCTAssertEqual(i.toggleAction, .zapretset(on: false))
        XCTAssertEqual(i.strategy, 2)
        XCTAssertTrue(i.strategyEnabled)
        XCTAssertTrue(i.checkEnabled)
        XCTAssertEqual(i.checkTitle, "Проверить YouTube и Discord")
        XCTAssertEqual(i.results.map { $0.name }, ["YouTube", "YouTube видео", "Discord API", "Discord CDN"])
        XCTAssertEqual(i.results.map { $0.valueText }, ["412\u{00A0}мс", "530\u{00A0}мс", "610\u{00A0}мс", "нет"])
        XCTAssertEqual(i.results.map { $0.tone }, [.ok, .ok, .ok, .err])
        XCTAssertEqual(i.results[0].footnote, "обработано zapret: 6\u{00A0}пак.")
        XCTAssertEqual(i.results[3].footnote, "не открывается")
        XCTAssertEqual(i.checkCaption, "Проверено сегодня 14:06 · Discord видит IP провайдера")
        XCTAssertFalse(i.needsFastPoll)
        XCTAssertEqual(i.details.map { $0.label }, ["Выбрано", "Служба nfqws", "Правила nftables", "Маршрут", "Обработано пакетов", "Версия"])
        XCTAssertEqual(i.details.map { $0.value }, ["включить", "работает", "есть", "напрямую (IP провайдера)", "18234\u{00A0}TCP · 5120\u{00A0}QUIC", "v72.5"])
        XCTAssertEqual(Zapret.pollInterval(try zap(SampleJSON.zapretOn)), 30)
    }

    func testZapretOtherStates() throws {
        let partial = Zapret.info(try zap(SampleJSON.zapretPartial), now: nowT)
        XCTAssertEqual(partial.phase, .partial)
        XCTAssertEqual(partial.tone, .warn)
        XCTAssertEqual(partial.summary, "Включён, но работает не полностью")
        XCTAssertEqual(partial.errorText, "Расхождение: режим включён, но служба не работает, маршрут PassWall не применён. Сторож попробует исправить в течение минуты.")
        XCTAssertNil(partial.counters)
        XCTAssertEqual(partial.details[1].value, "не работает")

        let fallback = Zapret.info(try zap(SampleJSON.zapretFallback), now: nowT)
        XCTAssertEqual(fallback.errorText, "nfqws не запускается — YouTube и Discord временно идут через VPN")
        XCTAssertEqual(fallback.checkCaption, "Проверка не удалась: VPN (Xray) не был запущен.")
        XCTAssertEqual(fallback.results, [])
        XCTAssertFalse(fallback.details.contains { $0.label == "Обработано пакетов" })

        let busy = Zapret.info(try zap(SampleJSON.zapretBusy), now: nowT)
        XCTAssertEqual(busy.phase, .busy)
        XCTAssertEqual(busy.summary, "Применяю… PassWall перезапускается")
        XCTAssertFalse(busy.toggleEnabled)
        XCTAssertFalse(busy.strategyEnabled)
        XCTAssertTrue(busy.checkEnabled)
        XCTAssertTrue(busy.needsFastPoll)
        XCTAssertNil(busy.errorText, "no «Расхождение» while busy")
        XCTAssertEqual(busy.strategy, 1)
        XCTAssertEqual(Zapret.pollInterval(try zap(SampleJSON.zapretBusy)), 3)

        let checking = Zapret.info(try zap(SampleJSON.zapretOffChecking), now: nowT)
        XCTAssertEqual(checking.phase, .off)
        XCTAssertEqual(checking.tone, .neutral)
        XCTAssertEqual(checking.summary, "YouTube и Discord — через VPN, как всё остальное")
        XCTAssertEqual(checking.errorText, "Расхождение: режим выключен, но часть правил ещё активна. Сторож уберёт их в течение минуты.")
        XCTAssertEqual(checking.checkTitle, "Проверяю…")
        XCTAssertFalse(checking.checkEnabled)
        XCTAssertTrue(checking.needsFastPoll)
        XCTAssertEqual(checking.details[1].value, "работает")
        XCTAssertFalse(checking.details.contains { $0.label == "Версия" }, "empty version is not shown")
        XCTAssertEqual(checking.toggleAction, .zapretset(on: true))

        let ni = Zapret.info(try zap(SampleJSON.zapretNotInstalled), now: nowT)
        XCTAssertEqual(ni.phase, .notInstalled)
        XCTAssertEqual(ni.errorText, "zapret не установлен на роутере (нет nfqws, списков или модуля ядра).")
        XCTAssertTrue(ni.showsControls)
        XCTAssertFalse(ni.toggleEnabled)
        XCTAssertFalse(ni.strategyEnabled)
        XCTAssertFalse(ni.checkEnabled)

        let absent = Zapret.info(try zap(SampleJSON.zapretAbsent), now: nowT)
        XCTAssertEqual(absent.phase, .absent)
        XCTAssertEqual(absent.summary, "zapret на роутере не установлен.")
        XCTAssertFalse(absent.showsControls)

        let loading = Zapret.info(nil, now: nowT)
        XCTAssertEqual(loading.phase, .loading)
        XCTAssertEqual(loading.summary, "Загружаю…")
        XCTAssertFalse(loading.showsControls)
        XCTAssertEqual(Zapret.pollInterval(nil), 30)

        // a check by the VPN, ok without zapret processing
        let vpnCheck = try zap(#"{"installed":true,"enabled":false,"strategy":3,"busy":false,"checking":false,"check":{"ts":1791800000,"via":"vpn","list":[{"name":"YouTube","ok":true,"code":"204","ms":90,"queued":0}]}}"#)
        let v = Zapret.info(vpnCheck, now: nowT)
        XCTAssertEqual(v.checkCaption, "Проверено вчера 14:13 · Discord видит IP VPN")
        XCTAssertEqual(v.results[0].footnote, "без обработки zapret")
        let unknownVia = try zap(#"{"installed":true,"check":{"ts":1791886000,"via":"unknown","list":[{"name":"YouTube","ok":false,"code":"000","ms":10000,"queued":0}]}}"#)
        XCTAssertEqual(Zapret.info(unknownVia, now: nowT).checkCaption, "Проверено сегодня 14:06")
    }

    func testZapretStrategies() throws {
        XCTAssertEqual(Zapret.strategies.map { $0.title }, ["1 · multisplit", "2 · fake + fakedsplit", "3 · hostfakesplit"])
        XCTAssertEqual(Zapret.strategyCheckDelays, [2, 4, 7])
        let on = try zap(SampleJSON.zapretOn)
        XCTAssertEqual(Zapret.verifyStrategy(requested: 2, state: on, isLastCheck: false), .applied(toast: "Стратегия 2 выбрана."))
        XCTAssertEqual(Zapret.verifyStrategy(requested: 3, state: on, isLastCheck: false), .pending)
        XCTAssertEqual(Zapret.verifyStrategy(requested: 3, state: on, isLastCheck: true), .failed(text: "Стратегия не применилась — роутер был занят. Попробуй ещё раз."))
        let busy = try zap(SampleJSON.zapretBusy)
        XCTAssertEqual(Zapret.verifyStrategy(requested: 1, state: busy, isLastCheck: false), .pending, "busy: not yet")
        XCTAssertEqual(Zapret.verifyStrategy(requested: 1, state: nil, isLastCheck: false), .pending)
    }

    func testTgws() throws {
        let on = Tgws.info(try decodeJSON(TgwsState.self, SampleJSON.tgwsOn))
        XCTAssertEqual(on.phase, .working)
        XCTAssertEqual(on.tone, .ok)
        XCTAssertEqual(on.summary, "Telegram на всех устройствах дома — через Cloudflare, мимо VPN, без настройки")
        XCTAssertEqual(on.summaryBold, "через Cloudflare, мимо VPN")
        XCTAssertEqual(on.counter, "3412\u{00A0}подкл.")
        XCTAssertTrue(on.isOn)
        XCTAssertTrue(on.showsToggle)
        XCTAssertEqual(on.toggleAction, .tgwsset(on: false))
        let starting = Tgws.info(try decodeJSON(TgwsState.self, SampleJSON.tgwsStarting))
        XCTAssertEqual(starting.phase, .starting)
        XCTAssertEqual(starting.summary, "Запускается… Пока прокси не работает, Telegram идёт через VPN")
        let off = Tgws.info(try decodeJSON(TgwsState.self, SampleJSON.tgwsOff))
        XCTAssertEqual(off.phase, .off)
        XCTAssertEqual(off.summary, "Выключен — Telegram идёт как обычно (через VPN)")
        XCTAssertEqual(off.toggleAction, .tgwsset(on: true))
        let waiting = Tgws.info(try decodeJSON(TgwsState.self, #"{"installed":true,"auto":false,"enabled":true,"running":true,"listening":true}"#))
        XCTAssertEqual(waiting.phase, .waitingRedirect)
        XCTAssertEqual(waiting.summary, "Прокси работает, перехват ещё не включён (сторож включит в течение минуты)")
        let absent = Tgws.info(try decodeJSON(TgwsState.self, SampleJSON.tgwsAbsent))
        XCTAssertEqual(absent.phase, .notInstalled)
        XCTAssertEqual(absent.summary, "Telegram-прокси на роутере не установлен.")
        XCTAssertFalse(absent.showsToggle)
        XCTAssertEqual(Tgws.info(try decodeJSON(TgwsState.self, #"{"installed":false}"#)).phase, .notInstalled)
        XCTAssertEqual(Tgws.info(nil).phase, .loading)
        XCTAssertEqual(Tgws.verifyDelays, [3, 8])
        let onState = try decodeJSON(TgwsState.self, SampleJSON.tgwsOn)
        XCTAssertEqual(Tgws.verifySwitch(requested: true, state: onState, isLastCheck: false), .applied)
        XCTAssertEqual(Tgws.verifySwitch(requested: false, state: onState, isLastCheck: false), .pending)
        XCTAssertEqual(Tgws.verifySwitch(requested: false, state: onState, isLastCheck: true), .failed(text: "Роутер не переключил прокси Telegram — попробуй ещё раз."))
    }

    func testServicesDirect() throws {
        let s = try decodeJSON(RouterStatus.self, SampleJSON.statusStage4)
        let rows = SvcDirect.rows(s)
        XCTAssertEqual(rows.map { $0.name }, ["YouTube", "Discord", "Telegram", "Хайпиксель"])
        XCTAssertEqual(rows.map { $0.isOn }, [false, false, false, true])
        XCTAssertEqual(rows[0].caption, "Домен www.youtube.com добавится в MyDirect.")
        XCTAssertEqual(rows[3].caption, "IP сервера добавится в MyDirect — игра пойдёт без VPN, пинг станет как «Напрямую».")
        XCTAssertEqual(rows[3].icon, "cube")
        XCTAssertEqual(rows[0].toggleAction, .svcdirect(name: "YouTube", on: true))
        XCTAssertEqual(rows[3].toggleAction, .svcdirect(name: "Хайпиксель", on: false))
        XCTAssertTrue(rows.allSatisfy { $0.isEditable })
        guard case .object(var o) = try JSONValue.parse(SampleJSON.statusStage4) else {
            return XCTFail("fixture")
        }
        o["targets"] = .null
        o["target_list"] = .array([.string("web|A&B|https://ab.example/"), .string("mc|Мир|mc.example.org:25565")])
        let odd = SvcDirect.rows(RouterStatus(json: .object(o)))
        XCTAssertEqual(odd.map { $0.host }, ["ab.example", "mc.example.org"])
        XCTAssertFalse(odd[0].isEditable)
        XCTAssertEqual(odd[0].editCaption, "Это имя нельзя изменить из приложения.")
        XCTAssertNil(odd[0].toggleAction)
        XCTAssertTrue(odd[1].isEditable)
        o["target_list"] = .array([])
        XCTAssertEqual(SvcDirect.rows(RouterStatus(json: .object(o))), [])
    }

    func testMyDirectInput() throws {
        let m = try decodeJSON(MyDirectList.self, SampleJSON.mydirect)
        XCTAssertEqual(MyDirect.normalize("  https://www.Ozon.ru/catalog?x=1 "), "ozon.ru")
        XCTAssertEqual(MyDirect.normalize("HTTP://Example.COM"), "example.com")
        XCTAssertEqual(MyDirect.normalize("www.site.ru/"), "site.ru")
        XCTAssertEqual(MyDirect.check("https://www.Ozon.ru/catalog", list: m), .ok("ozon.ru"))
        XCTAssertEqual(MyDirect.check("gosuslugi.ru", list: m), .alreadyListed("Этот сайт уже в списке."))
        XCTAssertEqual(MyDirect.check("сайт.рф", list: m), .invalid("Нужен домен вида site.ru"))
        XCTAssertEqual(MyDirect.check("", list: m), .invalid("Нужен домен вида site.ru"))
        XCTAssertEqual(MyDirect.check("example.com:8080", list: m), .invalid("Нужен домен вида site.ru"))
        XCTAssertEqual(MyDirect.check("localhost", list: nil), .invalid("Нужен домен вида site.ru"))
        XCTAssertEqual(MyDirect.check("ozon.ru", list: nil), .ok("ozon.ru"))
        XCTAssertTrue(MyDirect.isPrefixed("geosite:category-ru"))
        XCTAssertTrue(MyDirect.isPrefixed("full:a.ru"))
        XCTAssertFalse(MyDirect.isPrefixed("kinopoisk.ru"))
        XCTAssertFalse(MyDirect.isPrefixed(":x"))
        XCTAssertFalse(MyDirect.isPrefixed("Geo:x"))
        XCTAssertTrue(MyDirect.isRemovable("kinopoisk.ru", list: m))
        XCTAssertFalse(MyDirect.isRemovable("gosuslugi.ru", list: m), "only added items")
        XCTAssertFalse(MyDirect.isRemovable("geosite:category-ru", list: m))
    }

    func testMyDirectLists() throws {
        let m = try decodeJSON(MyDirectList.self, SampleJSON.mydirect)
        let i = MyDirect.info(m)
        XCTAssertEqual(i.countText, "5\u{00A0}записей")
        XCTAssertEqual(i.allTitle, "Весь список (5)")
        XCTAssertEqual(i.added, [MyDirectRow(domain: "kinopoisk.ru", isAdded: true, isRemovable: true)])
        XCTAssertNil(i.addedEmptyText)
        XCTAssertEqual(i.found.map { $0.domain }, ["kinopoisk.ru", "gosuslugi.ru", "sberbank.ru", "mc.example.net"])
        XCTAssertEqual(i.found.map { $0.isAdded }, [true, false, false, false])
        XCTAssertEqual(i.found.map { $0.isRemovable }, [true, false, false, false])
        XCTAssertEqual(i.found[0].removeAction, .dirdel(domain: "kinopoisk.ru"))
        XCTAssertNil(i.found[1].removeAction)
        XCTAssertNil(i.moreText)
        XCTAssertNil(i.notFoundText)
        let geo = MyDirect.info(m, query: " GEO ")
        XCTAssertEqual(geo.found, [MyDirectRow(domain: "geosite:category-ru", isAdded: false, isRemovable: false)])
        XCTAssertEqual(MyDirect.info(m, query: "zzz").notFoundText, "Не найдено.")
        let empty = MyDirect.info(MyDirectList(domains: [], added: []))
        XCTAssertEqual(empty.countText, "0\u{00A0}записей")
        XCTAssertEqual(empty.addedEmptyText, "Пока ничего — добавь сайт ниже.")
        XCTAssertEqual(empty.notFoundText, "Не найдено.")
        let many = MyDirectList(domains: (1...65).map { "site\($0).ru" }, added: ["site1.ru"])
        let big = MyDirect.info(many)
        XCTAssertEqual(big.found.count, 60)
        XCTAssertEqual(big.moreText, "…и ещё 5. Уточни поиск.")
        XCTAssertEqual(big.countText, "65\u{00A0}записей")
        XCTAssertEqual(MyDirect.info(MyDirectList(domains: ["a.ru"], added: [])).countText, "1\u{00A0}запись")
        XCTAssertEqual(MyDirect.info(MyDirectList(domains: ["a.ru", "b.ru"], added: [])).countText, "2\u{00A0}записи")
    }
